describe("renderReportMarkdown", () => {
  test("the development report", () => {
    expect(renderReportMarkdown(sampleReport("dev", 0.06))).toBe(DEV_MARKDOWN);
  });

  test("the test report, with the changed-annotations warning and no calibration", () => {
    const report = sampleReport("test", 0.06, {
      changed: {
        algorithmVersion: "0-old",
        generatedAt: "2026-09-01T00:00:00Z",
        testAnnotations: "f".repeat(64),
      },
    });
    const markdown = renderReportMarkdown(report);
    expect(markdown).toBe(TEST_MARKDOWN);
    expect(markdown).not.toContain("Calibration");
  });

  test("a null threshold shows n/a and keeps the calibration", () => {
    const markdown = renderReportMarkdown(sampleReport("dev", null));
    expect(markdown).toContain("| Match threshold (Oklab)  | not set (calibration only)");
    expect(markdown).toContain("| perceptual |                    n/a |                n/a |");
    expect(markdown).toContain("Perceptual minus population (first color): n/a.");
    expect(markdown).toContain(
      "| dev-001 | reference | perceptual | #d9822b     | n/a    | n/a   |",
    );
    expect(markdown).toContain("## Calibration (development set only)");
    expect(markdown).toContain("| 0.200+      |");
  });

  test("an uncommitted tree adds a warning after the header", () => {
    const markdown = renderReportMarkdown(sampleReport("dev", 0.06, { dirty: true }));
    expect(markdown).toContain(
      "\n\n**Warning:** generated from uncommitted changes in src/, package.json, or pnpm-lock.yaml.\n\n## Summary",
    );
    expect(renderReportMarkdown(sampleReport("dev", 0.06))).not.toContain("uncommitted");
  });

  test("an analysis error shows its code and misses", () => {
    const report = buildReport({
      set: "dev",
      header: sampleReport("dev", 0.06).header,
      measured: [
        {
          annotation: annotation("dev-004", "general", "#ffffff"),
          error: "DECODE_FAILED",
          perceptual: [],
          population: [],
          sampleDrift: false,
        },
      ],
      pending: 0,
      orphaned: 0,
      duplicates: 0,
    });
    const markdown = renderReportMarkdown(report);
    expect(markdown).toContain(
      "| dev-004 | general  | perceptual | error: DECODE_FAILED | miss   | miss  | -              |        - |",
    );
    expect(markdown).toContain("Analysis errors: 1.");
    expect(markdown).toContain("No images in the dark category.");
  });

  test("the same input renders identically, ends with one newline, and is ASCII outside the warning", () => {
    const report = sampleReport("dev", 0.06);
    const first = renderReportMarkdown(report);
    expect(renderReportMarkdown(report)).toBe(first);
    expect(first.endsWith("|\n")).toBe(true);
    expect(first).not.toContain("\r");
    expect(/[^\n\x20-\x7e]/.test(first)).toBe(false);
  });

  test("nothing in the report names a file or a path", () => {
    const text =
      renderReportMarkdown(sampleReport("dev", 0.06)) + renderReportJson(sampleReport("dev", 0.06));
    expect(text).not.toMatch(/\.(png|jpe?g|webp|avif)\b|relativePath/i);
  });

  test("number formats", () => {
    const report = sampleReport("dev", 0.06);
    const rendered = renderReportMarkdown({
      ...report,
      header: { ...report.header, threshold: 0.0005 },
    });
    expect(rendered).toContain("| Match threshold (Oklab)  | 0.001");
    const empty = renderReportMarkdown(
      buildReport({
        set: "dev",
        header: report.header,
        measured: [],
        pending: 0,
        orphaned: 0,
        duplicates: 0,
      }),
    );
    expect(empty).toContain("| perceptual |            0 / 0 (n/a) |        0 / 0 (n/a) |");
  });
});

describe("renderReportJson", () => {
  test("is the JSON of the report with two-space indentation and a final newline", () => {
    const report = sampleReport("dev", 0.06);
    const text = renderReportJson(report);
    expect(text).toBe(`${JSON.stringify(report, null, 2)}\n`);
    expect(text.endsWith("}\n")).toBe(true);
    expect(text.startsWith('{\n  "schemaVersion": 1,\n  "set": "dev",\n  "header": {\n')).toBe(
      true,
    );
    expect(JSON.parse(text)).toEqual(report);
    expect(parseReport(text, "report").set).toBe("dev");
  });

  test("renders identically twice", () => {
    const report = sampleReport("test", 0.06);
    expect(renderReportJson(report)).toBe(renderReportJson(report));
  });
});

describe("renderTable", () => {
  test("pads every column to its widest cell and aligns right with a colon", () => {
    expect(
      renderTable(
        ["Name", "Count"],
        ["left", "right"],
        [
          ["a", "1"],
          ["long name", "22"],
        ],
      ),
    ).toBe(
      [
        "| Name      | Count |",
        "| --------- | ----: |",
        "| a         |     1 |",
        "| long name |    22 |",
      ].join("\n"),
    );
  });

  test("a column is at least three characters wide", () => {
    expect(renderTable(["A", "B"], ["left", "right"], [["x", "y"]])).toBe(
      ["| A   |   B |", "| --- | --: |", "| x   |   y |"].join("\n"),
    );
  });

  test("throws on non-ASCII text, pipes, and rows of the wrong length", () => {
    expect(() => renderTable(["A"], ["left"], [["\u2192"]])).toThrow(RangeError);
    expect(() => renderTable(["A"], ["left"], [["a|b"]])).toThrow(RangeError);
    expect(() => renderTable(["A", "B"], ["left", "left"], [["x"]])).toThrow(RangeError);
  });
});
