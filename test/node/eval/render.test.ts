function annotation(id: string, category: Category, hex: string): ImageAnnotation {
  return {
    id,
    sha256: id.replace(/\D/g, "").padStart(64, "0"),
    category,
    width: 4,
    height: 4,
    acceptable: [{ samples: [{ x: 0, y: 0, hex }] }],
  };
}

function colors(hexes: string[], coverage = 0.25) {
  return hexes.map((hex) => ({ hex, coverage }));
}

function sampleReport(
  set: SetName,
  threshold: number | null,
  options: { changed?: PreviousReportRef | null; dirty?: boolean } = {},
) {
  const measured: MeasuredImage[] = [
    {
      annotation: annotation(`${set}-001`, "reference", "#d9822b"),
      error: null,
      perceptual: colors(["#d9822b", "#28aab4"]),
      population: colors(["#da822b", "#28aab4"]),
      sampleDrift: false,
    },
    {
      annotation: annotation(`${set}-002`, "dark", "#101010"),
      error: null,
      perceptual: colors(["#000000", "#0a0a0a", "#808080"], 0.2),
      population: colors(["#d9822b"]),
      sampleDrift: false,
    },
  ];
  return buildReport({
    set,
    header: {
      algorithmVersion: "1-test",
      packageVersion: "0.4.0-next.0",
      commit: "0123456789abcdef0123456789abcdef01234567",
      dirty: options.dirty ?? false,
      generatedAt: "2026-10-20T18:04:05Z",
      threshold,
      count: 5,
      decoder: { sharp: "0.35.5", libvips: "8.18.7" },
      annotations: { dev: "d".repeat(64), test: set === "test" ? "e".repeat(64) : null },
      testAnnotationsChanged: options.changed ?? null,
    },
    measured,
    pending: 3,
    orphaned: 1,
    duplicates: 0,
  });
}

