import { expect, test } from "vite-plus/test";
import { renderBenchMarkdown, type BenchReport } from "../../../bench/report.js";

const timing = (mean: number) => ({ mean, min: mean - 1, max: mean + 2, samples: 12 });
const options = { time: 2000, warmupTime: 500, iterations: 5, warmupIterations: 2 };

function sample(overrides: Partial<BenchReport> = {}): BenchReport {
  return {
    algorithmVersion: "3",
    packageVersion: "0.4.0-next.0",
    commit: "a".repeat(40),
    dirty: false,
    generatedAt: "2026-10-11T20:00:00Z",
    machine: {
      cpu: "Test CPU",
      cores: 10,
      memoryBytes: 16 * 1024 ** 3,
      platform: "darwin",
      release: "25.6.0",
      arch: "arm64",
    },
    nodeVersion: "v24.21.0",
    sharp: "0.35.5",
    libvips: "8.18.7",
    coverOptions: options,
    worstCaseOptions: { time: 0, warmupTime: 0, iterations: 3, warmupIterations: 1 },
    cases: [
      {
        label: "dev-004",
        format: "JPEG",
        width: 400,
        height: 300,
        population: timing(10),
        perceptual: timing(12.5),
      },
      {
        label: "synthetic worst case",
        format: "raw",
        width: 4096,
        height: 4096,
        population: timing(900),
        perceptual: timing(800),
      },
    ],
    ...overrides,
  };
}

test("renders the header, one row per case and mode, and the difference", () => {
  const markdown = renderBenchMarkdown(sample());
  expect(markdown.startsWith("# Benchmark report\n\nGenerated by `vp run bench`.")).toBe(true);
  expect(markdown.endsWith("|\n")).toBe(true);
  expect(markdown).toContain("| Algorithm version    | `3`");
  expect(markdown).toContain("16.0 GiB");
  expect(markdown).toContain("darwin 25.6.0 (arm64)");
  expect(markdown).toContain("sharp 0.35.5, libvips 8.18.7");
  expect(markdown).toContain("400 x 300");
  expect(markdown).toContain("16.78");
  expect(markdown).toContain("+2.50");
  expect(markdown).toContain("-100.00");
  expect(markdown).not.toContain("Warning");
  expect(markdown).not.toContain("\r");
});

test("marks a dirty run", () => {
  expect(renderBenchMarkdown(sample({ dirty: true }))).toContain(
    "**Warning:** generated from uncommitted changes",
  );
});

test("keeps tables printable ASCII", () => {
  const markdown = renderBenchMarkdown(
    sample({ machine: { ...sample().machine, cpu: "Chip | é" } }),
  );
  expect(markdown).toContain("Chip / ?");
});
