import {
  NEAR_BLACK_MAX_CHROMA,
  NEAR_BLACK_MAX_LIGHTNESS,
  DARK_DIAGNOSTIC_COLORS,
} from "../config.js";
import type { DarkDiagnostic } from "./match.js";
import type { ImageModeResult, ModeCounts, Report } from "./report-schema.js";

/** The JSON file: key order follows the interfaces, numbers were rounded by the builder. */
export function renderReportJson(report: Report): string {
  return `${JSON.stringify(report, null, 2)}\n`;
}

/**
 * A Markdown table with every column padded to its widest cell, like oxfmt pads them. The
 * alignment row uses `---:` for right-aligned columns.
 *
 * @throws RangeError for a non-ASCII character or a row of the wrong length.
 */
export function renderTable(
  headers: readonly string[],
  align: readonly ("left" | "right")[],
  rows: readonly (readonly string[])[],
): string {
  for (const row of [headers, ...rows]) {
    if (row.length !== headers.length) throw new RangeError("A row has the wrong number of cells.");
    for (const cell of row) {
      if (!/^[\x20-\x7e]*$/.test(cell)) {
        throw new RangeError("Table cells must be printable ASCII.");
      }
      if (cell.includes("|")) throw new RangeError("Table cells cannot contain a pipe.");
    }
  }
  const widths = headers.map((header, column) =>
    Math.max(3, header.length, ...rows.map((row) => row[column]?.length ?? 0)),
  );
  const line = (cells: readonly string[]): string =>
    `| ${cells
      .map((cell, column) =>
        align[column] === "right"
          ? cell.padStart(widths[column] ?? 0)
          : cell.padEnd(widths[column] ?? 0),
      )
      .join(" | ")} |`;
  const separator = `| ${widths
    .map((width, column) =>
      align[column] === "right" ? `${"-".repeat(width - 1)}:` : "-".repeat(width),
    )
    .join(" | ")} |`;
  return [line(headers), separator, ...rows.map(line)].join("\n");
}

const NOT_AVAILABLE = "n/a";

function percent(hits: number, measured: number): string {
  return measured === 0 ? NOT_AVAILABLE : `${((100 * hits) / measured).toFixed(1)}%`;
}

function hitsCell(hits: number | null, measured: number): string {
  return hits === null ? NOT_AVAILABLE : `${hits} / ${measured} (${percent(hits, measured)})`;
}

function plainHits(hits: number | null): string {
  return hits === null ? NOT_AVAILABLE : String(hits);
}

function outcome(hit: boolean | null): string {
  return hit === null ? NOT_AVAILABLE : hit ? "hit" : "miss";
}

function distance(value: number): string {
  return value.toFixed(3);
}

function signed(value: number): string {
  return value >= 0 ? `+${value}` : String(value);
}

function code(value: string): string {
  return `\`${value}\``;
}

function hash(value: string | null): string {
  return value === null ? "none" : code(value);
}

function firstColorCell(error: string | null, result: ImageModeResult): string {
  if (error !== null) return `error: ${error}`;
  return result.colors[0] ?? "-";
}

function darkCells(row: DarkDiagnostic): string[] {
  return [
    String(row.nearBlack),
    percent(row.coverage, 1),
    row.closestPair === null ? "-" : distance(row.closestPair),
  ];
}

/** The Markdown file of section 3.3: ASCII tables, "\n" line endings, and a final newline. */
export function renderReportMarkdown(report: Report): string {
  const { header, summary } = report;
  const isDev = report.set === "dev";
  const blocks: string[] = [];
  const add = (...lines: string[]): void => {
    blocks.push(lines.join("\n"));
  };

  add(`# Evaluation report: ${isDev ? "development" : "test"} set`);
  add(
    "Generated by `vp run eval`. Images are identified by neutral ids; file names and images are never published.",
  );
  add(
    renderTable(
      ["Field", "Value"],
      ["left", "left"],
      [
        ["Algorithm version", code(header.algorithmVersion)],
        ["Package version", code(header.packageVersion)],
        ["Commit", code(header.commit)],
        ["Date", header.generatedAt],
        [
          "Match threshold (Oklab)",
          header.threshold === null ? "not set (calibration only)" : distance(header.threshold),
        ],
        ["Colors per image", String(header.count)],
        ["Decoder", `sharp ${header.decoder.sharp}, libvips ${header.decoder.libvips}`],
        ["dev annotations SHA-256", hash(header.annotations.dev)],
        ["test annotations SHA-256", hash(header.annotations.test)],
      ],
    ),
  );
  const changed = header.testAnnotationsChanged;
  if (changed !== null) {
    add(
      `**Warning:** the test annotations changed since the report of ${code(changed.algorithmVersion)} (${changed.generatedAt}): SHA-256 ${hash(changed.testAnnotations)} → ${hash(header.annotations.test)}.`,
    );
  }
  if (header.dirty) {
    add(
      "**Warning:** generated from uncommitted changes in src/, package.json, or pnpm-lock.yaml.",
    );
  }

  const measured = summary.measured;
  add("## Summary");
  add(
    renderTable(
      ["Mode", "First color acceptable", "Within the first 3"],
      ["left", "right", "right"],
      (["perceptual", "population"] as const).map((mode) => [
        mode,
        hitsCell(summary[mode].firstHits, measured),
        hitsCell(summary[mode].top3Hits, measured),
      ]),
    ),
  );
  add(
    `Perceptual minus population (first color): ${
      summary.perceptualMinusPopulation === null
        ? NOT_AVAILABLE
        : `${signed(summary.perceptualMinusPopulation)} images`
    }.`,
  );
  add(
    `Measured: ${summary.measured}. Pending (image without annotation): ${summary.pending}. Orphaned (annotation without image): ${summary.orphaned}. Duplicate files: ${summary.duplicates}. Analysis errors: ${summary.errors}. Samples whose decoded pixel changed: ${summary.sampleDrift}.`,
  );

  const counts = (value: ModeCounts, key: keyof ModeCounts): string => plainHits(value[key]);
  add("## By category");
  add(
    renderTable(
      [
        "Category",
        "Images",
        "Perceptual first",
        "Population first",
        "Perceptual top 3",
        "Population top 3",
      ],
      ["left", "right", "right", "right", "right", "right"],
      report.categories.map((row) => [
        row.category,
        String(row.measured),
        counts(row.perceptual, "firstHits"),
        counts(row.population, "firstHits"),
        counts(row.perceptual, "top3Hits"),
        counts(row.population, "top3Hits"),
      ]),
    ),
  );

  if (isDev && report.calibration !== null) {
    add("## Calibration (development set only)");
    add(
      "Hits of the first color at candidate thresholds. The threshold is fixed before the test set is measured.",
    );
    add(
      renderTable(
        ["Threshold", "Perceptual first", "Population first"],
        ["right", "right", "right"],
        report.calibration.thresholds.map((row) => [
          distance(row.threshold),
          `${row.perceptual} / ${measured}`,
          `${row.population} / ${measured}`,
        ]),
      ),
    );
    add("Distance from the first color to the nearest acceptable sample:");
    add(
      renderTable(
        ["Distance", "Perceptual", "Population"],
        ["left", "right", "right"],
        report.calibration.distances.map((row) => [
          row.from === -1
            ? "no color"
            : row.to === null
              ? `${distance(row.from)}+`
              : `${distance(row.from)}-${distance(row.to)}`,
          String(row.perceptual),
          String(row.population),
        ]),
      ),
    );
  }

  add("## Dark images");
  if (report.dark.length === 0) {
    add("No images in the dark category.");
  } else {
    add(
      `Near-black: Oklab L < ${NEAR_BLACK_MAX_LIGHTNESS} and chroma < ${NEAR_BLACK_MAX_CHROMA}, among the first ${DARK_DIAGNOSTIC_COLORS} colors.`,
    );
    add(
      renderTable(
        [
          "Image",
          "Perceptual near-black",
          "Coverage",
          "Closest pair",
          "Population near-black",
          "Coverage",
          "Closest pair",
        ],
        ["left", "right", "right", "right", "right", "right", "right"],
        report.dark.map((row) => [
          row.id,
          ...darkCells(row.perceptual),
          ...darkCells(row.population),
        ]),
      ),
    );
  }

  add("## Images");
  add(
    renderTable(
      ["Image", "Category", "Mode", "First color", "Result", "Top 3", "Nearest sample", "Distance"],
      ["left", "left", "left", "left", "left", "left", "left", "right"],
      report.images.flatMap((image) =>
        (["perceptual", "population"] as const).map((mode) => {
          const result = image[mode];
          const failed = image.error !== null;
          return [
            image.id,
            image.category,
            mode,
            firstColorCell(image.error, result),
            failed ? "miss" : outcome(result.firstHit),
            failed ? "miss" : outcome(result.top3Hit),
            result.nearest === null ? "-" : result.nearest.hex,
            result.nearest === null ? "-" : distance(result.nearest.distance),
          ];
        }),
      ),
    ),
  );

  return `${blocks.join("\n\n")}\n`;
}
