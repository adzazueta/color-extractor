import { renderTable } from "../eval/lib/render.js";

/** Timing statistics of one mode in one case, in milliseconds. */
export interface ModeTiming {
  readonly mean: number;
  readonly min: number;
  readonly max: number;
  readonly samples: number;
}

/** A case is identified without file names: a neutral id for a cover, a description otherwise. */
export interface BenchCase {
  /** `dev-001` for a cover, a description for the synthetic case. */
  readonly label: string;
  /** JPEG, PNG, WebP, AVIF, or "raw" for raw pixels. */
  readonly format: string;
  readonly width: number;
  readonly height: number;
  readonly population: ModeTiming;
  readonly perceptual: ModeTiming;
}

export interface RunOptions {
  readonly time: number;
  readonly warmupTime: number;
  readonly iterations: number;
  readonly warmupIterations: number;
}

export interface BenchReport {
  readonly algorithmVersion: string;
  readonly packageVersion: string;
  readonly commit: string;
  readonly dirty: boolean;
  /** UTC ISO date, to the second. */
  readonly generatedAt: string;
  readonly machine: {
    readonly cpu: string;
    readonly cores: number;
    readonly memoryBytes: number;
    readonly platform: string;
    readonly release: string;
    readonly arch: string;
  };
  readonly nodeVersion: string;
  readonly sharp: string;
  readonly libvips: string;
  readonly coverOptions: RunOptions;
  readonly worstCaseOptions: RunOptions;
  readonly cases: readonly BenchCase[];
}

const code = (value: string): string => `\`${value}\``;

function ms(value: number): string {
  return value.toFixed(2);
}

function signedMs(value: number): string {
  const text = ms(Math.abs(value));
  return value < 0 ? `-${text}` : `+${text}`;
}

function options(value: RunOptions): string {
  return `time ${value.time} ms, warmup time ${value.warmupTime} ms, iterations ${value.iterations}, warmup iterations ${value.warmupIterations}`;
}

/** Keeps a table cell printable ASCII without a pipe. */
function plain(value: string): string {
  return value.replace(/[^\x20-\x7e]/g, "?").replace(/\|/g, "/");
}

/** The Markdown file of `vp run bench`: ASCII tables, "\n" line endings, and a final newline. */
export function renderBenchMarkdown(report: BenchReport): string {
  const blocks: string[] = [];
  const { machine } = report;
  blocks.push("# Benchmark report");
  blocks.push(
    "Generated by `vp run bench`. Covers are identified by neutral ids; file names and images are never published.",
  );
  blocks.push(
    renderTable(
      ["Field", "Value"],
      ["left", "left"],
      [
        ["Algorithm version", code(report.algorithmVersion)],
        ["Package version", code(report.packageVersion)],
        ["Commit", code(report.commit)],
        ["Date", report.generatedAt],
        ["CPU", plain(machine.cpu)],
        ["Cores", String(machine.cores)],
        ["Memory", `${(machine.memoryBytes / 1024 ** 3).toFixed(1)} GiB`],
        ["Operating system", plain(`${machine.platform} ${machine.release} (${machine.arch})`)],
        ["Node", plain(report.nodeVersion)],
        ["Decoder", `sharp ${plain(report.sharp)}, libvips ${plain(report.libvips)}`],
        ["Options (covers)", options(report.coverOptions)],
        ["Options (worst case)", options(report.worstCaseOptions)],
      ],
    ),
  );
  if (report.dirty) {
    blocks.push(
      "**Warning:** generated from uncommitted changes in src/, package.json, or pnpm-lock.yaml.",
    );
  }
  blocks.push("## Results");
  blocks.push(
    "Times are in milliseconds. For covers they include decoding plus extraction from the file bytes; for the synthetic case they cover extraction from raw pixels. All times are measured on the built package (`dist/node.js`).",
  );
  const header = [
    "Case",
    "Format",
    "Size",
    "MP",
    "Mode",
    "Mean (ms)",
    "Min (ms)",
    "Max (ms)",
    "Samples",
  ];
  const rows: string[][] = [];
  for (const item of report.cases) {
    const size = `${item.width} x ${item.height}`;
    const megapixels = ((item.width * item.height) / 1_000_000).toFixed(2);
    for (const mode of ["population", "perceptual"] as const) {
      const timing = item[mode];
      rows.push([
        plain(item.label),
        plain(item.format),
        size,
        megapixels,
        mode,
        ms(timing.mean),
        ms(timing.min),
        ms(timing.max),
        String(timing.samples),
      ]);
    }
  }
  blocks.push(
    renderTable(
      header,
      ["left", "left", "left", "right", "left", "right", "right", "right", "right"],
      rows,
    ),
  );
  blocks.push("## Perceptual minus population (mean)");
  blocks.push(
    renderTable(
      ["Case", "MP", "Difference (ms)"],
      ["left", "right", "right"],
      report.cases.map((item) => [
        plain(item.label),
        ((item.width * item.height) / 1_000_000).toFixed(2),
        signedMs(item.perceptual.mean - item.population.mean),
      ]),
    ),
  );
  return `${blocks.join("\n\n")}\n`;
}
